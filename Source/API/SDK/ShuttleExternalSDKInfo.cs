        public bool IsFeatureSupported(string featureKey)
        {
            if (string.IsNullOrWhiteSpace(featureKey) || this.SupportedFeatureKeys == null)
            {
                return false;
            }

            string normalized = featureKey.Trim();
            for (int i = 0; i < this.SupportedFeatureKeys.Count; i++)
            {
                if (this.SupportedFeatureKeys[i] == normalized)
                {
                    return true;
                }
            }

            return false;
        }
